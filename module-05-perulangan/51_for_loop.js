// Perulangan 'for' digunakan saat jumlah iterasi sudah diketahui sebelumnya
// Struktur: for (inisialisasi; kondisi; perubahan/iterasi)

console.log("=== Perulangan for Menghitung 1 sampai 5 ===");
for (let i = 1; i <= 5; i++) {
  console.log("Iterasi ke-" + i);
}

console.log("\n=== Perulangan for Mundur (Countdown) ===");
for (let i = 3; i >= 1; i--) {
  console.log("Hitung mundur:", i);
}
console.log("Meluncur!");
