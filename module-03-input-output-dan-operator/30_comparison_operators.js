// Operator Perbandingan (Comparison Operators)

const x = 10;
const y = 20;

console.log("Nilai x =", x, ", y =", y);
console.log("x > y  (Lebih besar)       :", x > y);
console.log("x < y  (Lebih kecil)       :", x < y);
console.log("x >= 10 (Lebih besar/sama) :", x >= 10);
console.log("y <= 15 (Lebih kecil/sama) :", y <= 15);
console.log("x == '10' (Equal value)    :", x == "10");
console.log("x != y (Tidak sama dengan) :", x != y);
