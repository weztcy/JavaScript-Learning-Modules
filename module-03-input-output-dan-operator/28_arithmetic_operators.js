// Operator Aritmetika dasar dalam JavaScript

const a = 15;
const b = 4;

console.log("Nilai a =", a, ", Nilai b =", b);
console.log("Penjumlahan (a + b) :", a + b);
console.log("Pengurangan (a - b) :", a - b);
console.log("Perkalian   (a * b) :", a * b);
console.log("Pembagian   (a / b) :", a / b);
console.log("Modulus     (a % b) :", a % b); // Sisa bagi: 15 % 4 = 3
console.log("Eksponen    (a ** b):", a ** b); // Pangkat: 15^4 = 50625
