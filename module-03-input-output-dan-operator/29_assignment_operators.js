// Operator Penugasan (Assignment Operators)

let nilai = 20;
console.log("Nilai awal        :", nilai);

nilai += 10; // setara dengan nilai = nilai + 10
console.log("Setelah += 10     :", nilai);

nilai -= 5;  // setara dengan nilai = nilai - 5
console.log("Setelah -= 5      :", nilai);

nilai *= 2;  // setara dengan nilai = nilai * 2
console.log("Setelah *= 2      :", nilai);

nilai /= 5;  // setara dengan nilai = nilai / 5
console.log("Setelah /= 5      :", nilai);

nilai %= 4;  // setara dengan nilai = nilai % 4
console.log("Setelah %= 4      :", nilai);
